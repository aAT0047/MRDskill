def draw_score_ridgeline(ax: plt.Axes, df: pd.DataFrame) -> None:
    hard = df[df["is_hard"]].copy()
    stages = [
        ("Feature", "score_Prompt_only_feature_adjudicator"),
        ("KG/RAG prior", "score_RAG_only_gene_prior"),
        ("Full plasma", "score_MRD_KGQC_plasma_only"),
    ]
    x = np.linspace(0, 1, 240)
    offsets = np.arange(len(stages))[::-1] * 1.0
    for offset, (label, score_col) in zip(offsets, stages):
        for truth, color in [(TUMOR, PALETTE["tumor"]), (CHIP, PALETTE["chip"])]:
            values = hard.loc[hard["binary_origin_label"] == truth, score_col].dropna().clip(0, 1).to_numpy(float)
            if gaussian_kde is not None and len(np.unique(values)) > 2:
                density = gaussian_kde(values)(x)
            else:
                hist, edges = np.histogram(values, bins=40, range=(0, 1), density=True)
                density = np.interp(x, (edges[:-1] + edges[1:]) / 2, hist)
            density = density / density.max() * 0.35
            ax.fill_between(x, offset, offset + density, color=color, alpha=0.28, lw=0)
            ax.plot(x, offset + density, color=color, lw=0.9)
        ax.text(-0.04, offset + 0.16, label, ha="right", va="center", fontsize=6.6, color=PALETTE["text"])
    ax.axvline(0.5, color=PALETTE["muted"], lw=0.8, ls="--")
    ax.set_xlim(0, 1)
    ax.set_ylim(-0.2, offsets.max() + 0.55)
    ax.set_yticks([])
    ax.set_xlabel("CHIP/WBC-origin score")
    ax.legend(
        handles=[
            plt.Line2D([0], [0], color=PALETTE["tumor"], lw=1.5, label="Tumor"),
            plt.Line2D([0], [0], color=PALETTE["chip"], lw=1.5, label="WBC/CHIP"),
        ],
        loc="upper left",
        frameon=False,
        ncol=2,
        bbox_to_anchor=(0.0, 1.04),
    )


