def ribbon(ax: plt.Axes, x0: float, x1: float, y0a: float, y0b: float, y1a: float, y1b: float, color: str, alpha: float = 0.35) -> None:
    verts = [
        (x0, y0a),
        ((x0 + x1) / 2, y0a),
        ((x0 + x1) / 2, y1a),
        (x1, y1a),
        (x1, y1b),
        ((x0 + x1) / 2, y1b),
        ((x0 + x1) / 2, y0b),
        (x0, y0b),
        (x0, y0a),
    ]
    codes = [
        MplPath.MOVETO,
        MplPath.CURVE4,
        MplPath.CURVE4,
        MplPath.CURVE4,
        MplPath.LINETO,
        MplPath.CURVE4,
        MplPath.CURVE4,
        MplPath.CURVE4,
        MplPath.CLOSEPOLY,
    ]
    ax.add_patch(PathPatch(MplPath(verts, codes), facecolor=color, edgecolor="none", alpha=alpha))


def draw_error_alluvial(ax: plt.Axes, flow: pd.DataFrame) -> None:
    categories = ["Correct", "Missed WBC/CHIP", "Tumor false suppression", "Review"]
    colors = {
        "Correct": PALETTE["blue"],
        "Missed WBC/CHIP": PALETTE["orange"],
        "Tumor false suppression": PALETTE["red"],
        "Review": PALETTE["grey"],
        "Other": PALETTE["muted"],
    }
    stages = [("Rule", "cat1"), ("MRDskill", "cat2"), ("Review", "cat3")]
    total = flow["count"].sum()
    x_positions = [0.10, 0.50, 0.90]
    stage_spans: list[dict[str, tuple[float, float]]] = []
    for _, cat_col in stages:
        counts = flow.groupby(cat_col)["count"].sum().to_dict()
        y_cursor = 0.05
        spans = {}
        for cat in categories:
            count = counts.get(cat, 0)
            if count == 0:
                continue
            height = count / total * 0.88
            spans[cat] = (y_cursor, y_cursor + height)
            y_cursor += height + 0.012
        stage_spans.append(spans)
    outgoing = [defaultdict(float) for _ in stages]
    incoming = [defaultdict(float) for _ in stages]
    pair12 = flow.groupby(["cat1", "cat2"])["count"].sum().reset_index()
    pair23 = flow.groupby(["cat2", "cat3"])["count"].sum().reset_index()
    for pair, i0, i1, c0, c1 in [(pair12, 0, 1, "cat1", "cat2"), (pair23, 1, 2, "cat2", "cat3")]:
        for _, row in pair.iterrows():
            cat0, cat1 = row[c0], row[c1]
            if cat0 not in stage_spans[i0] or cat1 not in stage_spans[i1]:
                continue
            h = row["count"] / total * 0.88
            s0 = stage_spans[i0][cat0]
            s1 = stage_spans[i1][cat1]
            y0a = s0[0] + outgoing[i0][cat0]
            y0b = y0a + h
            outgoing[i0][cat0] += h
            y1a = s1[0] + incoming[i1][cat1]
            y1b = y1a + h
            incoming[i1][cat1] += h
            ribbon(ax, x_positions[i0] + 0.025, x_positions[i1] - 0.025, y0a, y0b, y1a, y1b, colors.get(cat1, PALETTE["muted"]), 0.26)
    for (stage_label, _), x, spans in zip(stages, x_positions, stage_spans):
        ax.text(x, 0.98, stage_label, ha="center", va="top", fontsize=6.8, color=PALETTE["text"])
        for cat, (y0, y1) in spans.items():
            ax.add_patch(Rectangle((x - 0.025, y0), 0.05, y1 - y0, color=colors.get(cat, PALETTE["muted"]), alpha=0.85, lw=0))
            if y1 - y0 > 0.05:
                ax.text(x + 0.04, (y0 + y1) / 2, cat.replace("Tumor false ", "Tumor\nfalse "), ha="left", va="center", fontsize=5.9)
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis("off")


