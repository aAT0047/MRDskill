from __future__ import annotations

import argparse
import csv
import hashlib
import html
import json
import re
import time
from pathlib import Path
from typing import Any

from pdfminer.high_level import extract_text


def short_stem(pdf_path: Path) -> str:
    digest = hashlib.sha1(pdf_path.name.encode("utf-8")).hexdigest()[:12]
    match = re.match(r"^(KWRAW-\d+)", pdf_path.stem)
    if match:
        prefix = match.group(1)
    else:
        prefix = re.sub(r"[^A-Za-z0-9]+", "_", pdf_path.stem).strip("_")[:32] or "pdf"
    return f"{prefix}__{digest}"


def output_paths(output_dir: Path, stem: str) -> dict[str, Path]:
    return {
        "html": output_dir / f"{stem}.html",
        "json": output_dir / f"{stem}.json",
        "text": output_dir / f"{stem}.txt",
    }


def converted(output_dir: Path, stem: str) -> bool:
    paths = output_paths(output_dir, stem)
    return all(path.exists() and path.stat().st_size > 0 for path in paths.values())


def append_manifest(path: Path, row: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    exists = path.exists()
    with path.open("a", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(row.keys()))
        if not exists:
            writer.writeheader()
        writer.writerow(row)


def render_html(pdf_path: Path, page_texts: list[str]) -> str:
    title = html.escape(pdf_path.name)
    sections = []
    for index, page_text in enumerate(page_texts, start=1):
        escaped = html.escape(page_text.strip())
        sections.append(f'<section class="page" data-page="{index}"><h2>Page {index}</h2><pre>{escaped}</pre></section>')
    body = "\n".join(sections)
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{title}</title>
<style>
body {{ font-family: Arial, sans-serif; margin: 2rem; line-height: 1.45; }}
h1 {{ font-size: 1.25rem; }}
h2 {{ font-size: 1rem; margin-top: 2rem; }}
pre {{ white-space: pre-wrap; word-wrap: break-word; font-family: Consolas, monospace; font-size: 0.9rem; }}
.note {{ color: #555; }}
</style>
</head>
<body>
<h1>{title}</h1>
<p class="note">Generated by pdfminer fallback after opendataloader-pdf timed out. Text is extraction-oriented; layout and images are not preserved.</p>
{body}
</body>
</html>
"""


def convert_pdf(pdf_path: Path, output_dir: Path, overwrite: bool) -> tuple[str, str, dict[str, Path]]:
    stem = short_stem(pdf_path)
    outputs = output_paths(output_dir, stem)
    if not overwrite and converted(output_dir, stem):
        return "success", "already_converted", outputs

    text = extract_text(str(pdf_path)) or ""
    page_texts = [page.strip() for page in text.split("\f") if page.strip()]
    if not page_texts and text.strip():
        page_texts = [text.strip()]
    if not page_texts:
        return "failed", "no_text_extracted", outputs

    outputs["text"].write_text(text.strip() + "\n", encoding="utf-8")
    outputs["html"].write_text(render_html(pdf_path, page_texts), encoding="utf-8")
    payload = {
        "source_pdf": str(pdf_path),
        "source_filename": pdf_path.name,
        "converter": "pdfminer_fallback",
        "note": "Fallback conversion for PDFs that timed out in opendataloader-pdf; layout and images are not preserved.",
        "page_count": len(page_texts),
        "pages": [{"page_number": index, "text": page_text} for index, page_text in enumerate(page_texts, start=1)],
    }
    outputs["json"].write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return "success", "pdfminer_fallback", outputs


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input-dir", required=True)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--progress-every", type=int, default=1)
    args = parser.parse_args()

    input_dir = Path(args.input_dir).resolve()
    output_dir = Path(args.output_dir).resolve()
    manifest = Path(args.manifest).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    pdfs = sorted(input_dir.glob("*.pdf"))
    for index, pdf_path in enumerate(pdfs, start=1):
        started = time.time()
        try:
            status, reason, outputs = convert_pdf(pdf_path, output_dir, args.overwrite)
        except Exception as exc:  # noqa: BLE001
            stem = short_stem(pdf_path)
            outputs = output_paths(output_dir, stem)
            status = "failed"
            reason = f"{type(exc).__name__}: {exc}"
        elapsed = round(time.time() - started, 3)
        if index == 1 or index == len(pdfs) or index % args.progress_every == 0 or status != "success":
            print(f"[{index}/{len(pdfs)}] {status}: {pdf_path.name} ({elapsed}s)", flush=True)
        append_manifest(
            manifest,
            {
                "source_pdf": str(pdf_path),
                "source_filename": pdf_path.name,
                "source_dir": input_dir.name,
                "output_dir": str(output_dir),
                "output_stem": short_stem(pdf_path),
                "html_path": str(outputs["html"]) if outputs["html"].exists() else "",
                "json_path": str(outputs["json"]) if outputs["json"].exists() else "",
                "text_path": str(outputs["text"]) if outputs["text"].exists() else "",
                "status": status,
                "reason": reason,
                "elapsed_seconds": elapsed,
                "sequence_index": index,
                "converter": "pdfminer_fallback",
            },
        )


if __name__ == "__main__":
    main()
